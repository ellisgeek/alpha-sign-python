"""Extract the font character sets of Appendix O (pp. 141-216) from the Alpha protocol PDF.

One-off tool, kept for reproducibility. Run from the repo root:

    uv run --no-project --with pymupdf python docs/reference/extract_fonts.py \
        docs/reference/M-Protocol.pdf emulator/src/core/display/manual-glyphs.ts

Each glyph in Appendix O is a frame holding one dot per pixel of the character cell
(dark = lit, white = off), with its label (CHR065, ...) just below the frame. The
glyphs are vector drawings, so text extraction sees only the labels. Fonts are told
apart by their "7.15.N" section headings, not by page footers, because a font can end
partway down a page. Only codes 20H-7FH are kept; the emulator does not model the
extended characters.
"""

import json
import re
import sys

import pymupdf

PAGES = range(141, 217)
LABEL = re.compile(r"(CHR|CR|F?FAT|FTS|SFT)\w*!?")
CODED = re.compile(r"CHR(\d{3})")
# The fonts the 4000 Series can select (Table 69), by the code in their heading.
KEEP = {"SS5", "SS7", "SF7", "SF10", "SS15", "SF15", "SS16", "SF16"}


def clusters(values, dot):
    """Centres of runs of values that lie within half a dot of each other."""
    runs = []
    for v in sorted(values):
        if runs and v - runs[-1][-1] < dot / 2:
            runs[-1].append(v)
        else:
            runs.append([v])
    return [sum(r) / len(r) for r in runs]


def nearest(centres, v):
    return min(range(len(centres)), key=lambda i: abs(centres[i] - v))


def page_items(page, number):
    """The page's section headings and glyphs, each with its position."""
    drawings = page.get_drawings()
    widths = [
        round(x["rect"].width, 1)
        for x in drawings
        if x["type"] == "fs" and x["rect"].width < 20 and abs(x["rect"].width - x["rect"].height) < 0.2
    ]
    dot = max(set(widths), key=widths.count)
    frames = [x["rect"] for x in drawings if x["type"] == "f" and x["rect"].width > 60]
    dots = []
    for x in drawings:
        r = x["rect"]
        # Most dots are one fill-and-stroke path; SF15's "&" (p. 190) uses separate ones.
        if x["type"] in ("fs", "f") and abs(r.width - dot) < 0.3 and abs(r.height - dot) < 0.3:
            fill = x.get("fill") or (1, 1, 1)
            dots.append(((r.x0 + r.x1) / 2, (r.y0 + r.y1) / 2, sum(fill) / 3 < 0.5))
    words = page.get_text("words")
    labels = [w for w in words if LABEL.fullmatch(w[4])]
    items = []
    for w in words:
        if re.fullmatch(r"7\.15\.\d+", w[4]):
            line = " ".join(v[4] for v in words if abs(v[1] - w[1]) < 2 and v[0] > w[0])
            items.append((w[1], 0, 0, ("heading", line)))
    for f in frames:
        inside = [d for d in dots if f.x0 <= d[0] <= f.x1 and f.y0 <= d[1] <= f.y1]
        if not inside:
            continue
        # The label sits just below the frame (on p. 194 it overlaps the edge).
        below = {w[4] for w in labels if f.x0 <= (w[0] + w[2]) / 2 <= f.x1 and -3 <= w[1] - f.y1 <= 15}
        if len(below) != 1:
            raise SystemExit(f"p. {number}: frame {tuple(f)} has labels {sorted(below)}")
        xs, ys = clusters([d[0] for d in inside], dot), clusters([d[1] for d in inside], dot)
        grid = [["0"] * len(xs) for _ in ys]
        for x, y, lit in inside:
            if lit:  # some dots are drawn twice at one spot; a lit one wins
                grid[nearest(ys, y)][nearest(xs, x)] = "1"
        items.append((f.y0, 1, f.x0, ("glyph", below.pop(), ["".join(row) for row in grid])))
    # Reading order: by row of the page, a heading before the glyphs that follow it.
    return sorted(items, key=lambda i: (round(i[0] / 20), i[1], i[2]))


def extract(path):
    doc = pymupdf.open(path)
    fonts: dict[str, dict[str, list[str]]] = {}
    current = None
    for number in PAGES:
        for _, _, _, item in page_items(doc[number - 1], number):
            if item[0] == "heading":
                code = re.search(r"\((S[SF]\d+)\)", item[1])
                current = code.group(1) if code else None
                if current in KEEP:
                    fonts[current] = {}
                continue
            if current not in KEEP:
                continue
            _, label, rows = item
            coded = CODED.fullmatch(label)
            if not coded or not 0x20 <= int(coded.group(1)) <= 0x7F:
                continue
            char = chr(int(coded.group(1)))
            if char in fonts[current]:
                print(f"{current}: a second {label}, kept the first", file=sys.stderr)
                continue
            fonts[current][char] = rows
    return fonts


def typescript(fonts):
    lines = [
        "// Generated by docs/reference/extract_fonts.py from Appendix O (pp. 141-216) of",
        "// the protocol manual (docs/reference/M-Protocol.pdf). Do not edit by hand.",
        "//",
        "// Each font maps a character (20H-7FH) to its cell, rows top to bottom, 1 = lit,",
        "// rows separated by spaces. Cells are fixed width; the emulator trims blank",
        "// columns to space characters proportionally.",
        "",
        "export const MANUAL_GLYPHS: Readonly<Record<string, Readonly<Record<string, string>>>> = {",
    ]
    for code, glyphs in fonts.items():
        lines.append(f"  {code}: {{")
        for char in sorted(glyphs):
            lines.append(f"    {json.dumps(char)}: {json.dumps(' '.join(glyphs[char]))},")
        lines.append("  },")
    lines.append("};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    fonts = extract(sys.argv[1])
    with open(sys.argv[2], "w") as out:
        out.write(typescript(fonts))
    for code, glyphs in fonts.items():
        missing = "".join(chr(c) for c in range(0x21, 0x7F) if chr(c) not in glyphs)
        heights = sorted({len(g) for g in glyphs.values()})
        print(f"{code}: {len(glyphs)} glyphs, heights {heights}, missing {missing!r}")
